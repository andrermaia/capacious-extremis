#!/usr/bin/env node
// Renders the universal agent rules (knowledge base, project "global", module "rules")
// and the context protocol into every agent's instruction file:
//   ~/.claude/CLAUDE.md          rules                       (Claude Code, any folder)
//   ~/.codex/AGENTS.md           rules + protocol            (Codex, when ~/.codex exists; short when its hooks are installed)
//   ~/.gemini/GEMINI.md          rules + protocol            (Gemini/agy, same)
//   ~/.kimi-code/AGENTS.md       rules + protocol            (Kimi Code, same)
//   <root>/CLAUDE.md             protocol with hooks         (when the skill sits in <root>/.agents/skills)
//   <root>/AGENTS.md             short protocol + where the rules and manual protocol are
// Each file gets one block between markers; text outside the block is kept. A file
// that still holds a hand-written copy of the protocol is replaced whole, after a backup.
// Usage: node sync-rules.mjs [--home <dir>] [--root <dir> | --no-root] [--dry-run] [--quiet]
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { optedIn } from './self-update.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const skillDir = path.resolve(here, '..');
const cliPath = path.join(skillDir, 'scripts', 'context-cli.mjs');

export const BEGIN = '<!-- capacious-extremis:begin — generated by sync-rules; edit the rules in the knowledge base (project global, module rules), not here -->';
export const END = '<!-- capacious-extremis:end -->';
// Hand-written copies that predate sync-rules: replaced whole on the first sync.
const LEGACY = [/System Context & Knowledge Management/, /installed by Maestro/i];

const CATEGORY_ORDER = ['communication', 'autonomy', 'verification', 'git', 'environment', 'security', 'knowledge'];
const title = (s) => s.charAt(0).toUpperCase() + s.slice(1).replace(/[-_]/g, ' ');

function parseArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    const key = argv[i].replace(/^--/, '');
    if (['dry-run', 'quiet', 'no-root'].includes(key)) opts[key] = true;
    else opts[key] = argv[++i];
  }
  return opts;
}

// The skill normally lives in <root>/.agents/skills/managing-system-context; in the cloud
// it lives in ~/.agents/..., and then there is no project root to write to.
function defaultRoot(home) {
  const parts = skillDir.split(path.sep);
  if (parts.slice(-3).join('/') !== '.agents/skills/managing-system-context') return null;
  const root = parts.slice(0, -3).join(path.sep);
  return path.resolve(root) === path.resolve(home) ? null : root;
}

export function fetchRules() {
  const res = spawnSync(process.execPath, [cliPath, 'query', '--project', 'global', '--module', 'rules', '--json'], {
    encoding: 'utf8', windowsHide: true, timeout: 15000,
  });
  let rows;
  try {
    rows = JSON.parse(res.stdout);
  } catch {
    throw new Error(`could not read the rules: ${(res.stderr || res.stdout || '').split('\n').find((l) => l.trim() && !/Warning|trace-warnings/.test(l)) || `exit ${res.status}`}`);
  }
  if (!Array.isArray(rows)) throw new Error(`unexpected answer: ${String(res.stdout).slice(0, 200)}`);
  return rows.filter((r) => r.phase !== 'deprioritized');
}

export function renderRules(rules) {
  const byCategory = new Map();
  for (const r of rules) {
    const key = String(r.feature || 'general').toLowerCase();
    if (!byCategory.has(key)) byCategory.set(key, []);
    byCategory.get(key).push(r);
  }
  const rank = (k) => (CATEGORY_ORDER.includes(k) ? CATEGORY_ORDER.indexOf(k) : CATEGORY_ORDER.length);
  const keys = [...byCategory.keys()].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const lines = [
    '## Universal agent rules',
    '',
    'They apply to every agent, in every project and folder. Source: the shared knowledge base, project `global`, module `rules`; change one with `context-cli upsert --project global --module rules ...`, retire it with `--phase deprioritized`.',
  ];
  for (const k of keys) {
    lines.push('', `### ${title(k)}`);
    for (const r of byCategory.get(k).sort((a, b) => a.id.localeCompare(b.id))) lines.push(`- ${r.summary}`);
  }
  return lines.join('\n');
}

function template(name, vars) {
  let text = fs.readFileSync(path.join(skillDir, 'rules', name), 'utf8').trim();
  for (const [k, v] of Object.entries(vars)) text = text.split(`{{${k}}}`).join(v);
  return text;
}

export function planTargets({ home, root, rulesBlock }) {
  const manual = (rootDir) => template('protocol-manual.md', {
    ROOT: rootDir || '(no project root)',
    CLI: cliPath.split(path.sep).join('/'),
  });
  // An agent whose hooks are installed gets the short protocol (the hooks inject the rest each
  // session); only one without hooks needs the manual one. Every agent's own file carries the
  // rules, so the root AGENTS.md (read by Codex and Kimi on top of their own) carries no copy.
  const hooked = optedIn(home);
  const withHooks = template('protocol-hooks.md', {});
  // ~/.claude/CLAUDE.md never counts as a legacy copy: in the cloud it also holds the
  // protocol written by cloud/install.mjs, which must stay.
  const targets = [{ file: path.join(home, '.claude', 'CLAUDE.md'), body: rulesBlock, legacy: false }];
  for (const [dir, name, agent] of [['.codex', 'AGENTS.md', 'codex'], ['.gemini', 'GEMINI.md', 'agy'], ['.kimi-code', 'AGENTS.md', 'kimi']]) {
    if (fs.existsSync(path.join(home, dir))) {
      const protocol = root ? (hooked[agent] ? withHooks : manual(root)) : '';
      targets.push({ file: path.join(home, dir, name), body: protocol ? `${rulesBlock}\n\n${protocol}` : rulesBlock, legacy: true });
    }
  }
  if (root) {
    targets.push({ file: path.join(root, 'CLAUDE.md'), body: withHooks, legacy: true, heading: '# Global Agent Rules' });
    const cli = cliPath.split(path.sep).join('/');
    const manualFile = path.join(skillDir, 'rules', 'protocol-manual.md').split(path.sep).join('/');
    targets.push({ file: path.join(root, 'AGENTS.md'), legacy: true, heading: '# Global Agent Rules',
      body: `${withHooks}\n\nAn agent without these hooks: read the universal rules (\`node ${cli} query --project global --module rules\`) and follow the manual protocol in \`${manualFile}\` (\`{{CLI}}\` there is \`node ${cli}\`) before working.` });
  }
  return targets;
}

const hasBlock = (text) => text.includes(BEGIN.slice(0, 30)) && text.includes(END);
const isLegacy = (text, target) => target.legacy && !hasBlock(text) && LEGACY.some((re) => re.test(text));

// New file content for one target, or null when nothing changes.
export function merge(current, target) {
  const { body, heading } = target;
  const block = `${BEGIN}\n${body}\n${END}`;
  if (current == null) return `${heading ? `${heading}\n\n` : ''}${block}\n`;
  const start = current.indexOf(BEGIN.slice(0, 30));
  const end = current.indexOf(END);
  let next;
  if (start >= 0 && end > start) {
    next = current.slice(0, start) + block + current.slice(end + END.length);
  } else if (isLegacy(current, target)) {
    next = `${heading ? `${heading}\n\n` : ''}${block}\n`;
  } else {
    next = `${current.replace(/\s*$/, '')}\n\n${block}\n`;
  }
  return next === current ? null : next;
}

function writeAtomic(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

export function sync({ home = os.homedir(), root, dryRun = false, rules } = {}) {
  const active = rules || fetchRules();
  if (!active.length) throw new Error('no active rule in project global, module rules: nothing written');
  const rulesBlock = renderRules(active);
  const report = { status: 'ok', rules: active.length, written: [], unchanged: [], backups: [] };
  for (const target of planTargets({ home, root, rulesBlock })) {
    const current = fs.existsSync(target.file) ? fs.readFileSync(target.file, 'utf8') : null;
    const next = merge(current, target);
    if (next == null) { report.unchanged.push(target.file); continue; }
    if (!dryRun) {
      if (current != null && isLegacy(current, target)) {
        const backup = `${target.file}.bak-${new Date().toISOString().slice(0, 10)}`;
        if (!fs.existsSync(backup)) fs.writeFileSync(backup, current);
        report.backups.push(backup);
      }
      writeAtomic(target.file, next);
    }
    report.written.push(target.file);
  }
  return report;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  const home = opts.home || os.homedir();
  const root = opts['no-root'] ? null : (opts.root || defaultRoot(home));
  try {
    const report = sync({ home, root, dryRun: opts['dry-run'] });
    if (!opts.quiet) console.log(JSON.stringify(report, null, 2));
  } catch (err) {
    console.error(JSON.stringify({ status: 'error', error: err.message }));
    process.exitCode = 1;
  }
}
